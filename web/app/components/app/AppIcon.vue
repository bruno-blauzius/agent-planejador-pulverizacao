  const iconPaths: readonly string[] | undefined = ICON_PATHS[props.name]
  // Names can arrive untyped (e.g. Vuetify aliases); flag them in dev instead of an empty SVG.
  if (!iconPaths && import.meta.dev) console.warn(`[AppIcon] unknown icon "${String(props.name)}"`)
  return iconPaths ?? []
})
</script>

